"""Run Stage 23 against pinned embedding models and a single freshly built corpus."""

import argparse
import gc
import hashlib
import json
import platform
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path
from time import perf_counter

import numpy as np
import torch

from backend.app.config import Settings
from backend.app.embeddings.sentence_transformer import SentenceTransformerEmbedder
from backend.app.evaluation.dataset import SourceEvaluationQuery, read_queries, resolve_queries
from backend.app.evaluation.embedding import (
    EmbeddingBenchmarkResult,
    EmbeddingProfile,
    benchmark_embedding,
)
from backend.app.ingestion.chunkers import HuggingFaceTokenCodec, RecursiveChunker
from backend.app.ingestion.parser import load_documents
from backend.app.ingestion.pipeline import build_chunks
from backend.app.llm.generation import _synchronize

PROJECT_ROOT = Path(__file__).resolve().parents[1]


def _path(value: Path) -> Path:
    return value if value.is_absolute() else PROJECT_ROOT / value


def _positive(value: str) -> int:
    number = int(value)
    if number <= 0:
        raise argparse.ArgumentTypeError("must be positive")
    return number


def _nonnegative(value: str) -> int:
    number = int(value)
    if number < 0:
        raise argparse.ArgumentTypeError("must be nonnegative")
    return number


def build_parser() -> argparse.ArgumentParser:
    settings = Settings()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--profiles", type=Path, default=Path("data/evaluation/embedding_profiles.json")
    )
    parser.add_argument("--corpus", type=Path, default=Path("data/raw"))
    parser.add_argument(
        "--queries", type=Path, default=Path("data/evaluation/retrieval_queries_source.jsonl")
    )
    parser.add_argument("--device", choices=["auto", "cpu", "mps", "cuda"], default="cpu")
    parser.add_argument("--repetitions", type=_positive, default=3)
    parser.add_argument("--warmup-runs", type=_nonnegative, default=1)
    parser.add_argument("--top-k", type=_positive, default=5)
    parser.add_argument("--chunk-size", type=_positive, default=settings.chunk_size_tokens)
    parser.add_argument("--overlap", type=_nonnegative, default=settings.chunk_overlap_tokens)
    parser.add_argument(
        "--output", type=Path, default=Path("evaluation/reports/embedding_benchmark.json")
    )
    parser.add_argument("--markdown", type=Path, default=Path("docs/embedding-benchmark.md"))
    return parser


def render_markdown(results: list[EmbeddingBenchmarkResult], top_k: int, created: str) -> str:
    lines = [
        "# Stage 23 — Embedding Benchmark",
        "",
        f"Measured at `{created}`. Generated by `python -m scripts.benchmark_embeddings`.",
        "",
        "The same recursive chunks, source-anchor labels and cosine Qdrant search are used for",
        "every pinned encoder. Model loading is separate. Warmups are excluded. Embedding",
        "timers include conversion back to CPU/Python; index build includes document encoding.",
        "",
        f"| Profile | Dim | Recall@{top_k} | Hit@{top_k} | MRR@{top_k} | NDCG@{top_k} |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    key = str(top_k)
    for result in results:
        metrics = [run.metrics for run in result.retrieval_runs]
        values = [
            float(np.mean([getattr(metric, name)[key] for metric in metrics]))
            for name in ("recall_at_k", "hit_rate_at_k", "mrr_at_k", "ndcg_at_k")
        ]
        lines.append(
            f"| {result.profile.name} | {result.dimension} | "
            + " | ".join(f"{value:.4f}" for value in values)
            + " |"
        )
    lines.extend(
        [
            "",
            "| Profile | Load ms | Encode corpus p50 ms | Docs/s | Query encode p50 / p95 ms | "
            "Search p50 / p95 ms | Raw vectors KiB |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
    )
    for result in results:
        lines.append(
            f"| {result.profile.name} | {result.model_load_ms:.1f} | "
            f"{result.document_embedding.p50_ms:.1f} | "
            f"{result.document_embeddings_per_second:.1f} | "
            f"{result.query_embedding.p50_ms:.2f} / {result.query_embedding.p95_ms:.2f} | "
            f"{result.retrieval_latency.p50_ms:.2f} / {result.retrieval_latency.p95_ms:.2f} | "
            f"{result.raw_float32_vector_bytes / 1024:.1f} |"
        )
    lines.extend(
        [
            "",
            "Recall is the fraction of labeled chunks found; Hit Rate is whether any labeled",
            "chunk was found. Quality averages exclude unanswerable queries, while latency includes",
            "all queries. The versioned source labels resolve one representative chunk per anchor,",
            "so alternative relevant overlapping chunks can be unjudged. This small English corpus",
            "does not establish multilingual or general model superiority. p95 values are descriptive",
            "sample percentiles, not production service guarantees. Profile order is recorded in JSON;",
            "load time is cache-dependent and is not a cold-download measurement. Raw vector bytes",
            "exclude Qdrant payloads/index structures and Python overhead; parameter bytes are not peak RAM.",
            "",
            "The JSON report contains all repeated rankings, individual timings, data fingerprints,",
            "encoder revisions, batching and environment metadata. Default grid: MiniLM L6/L12 ×",
            "batch sizes 8/32; three measured repetitions after one warmup.",
            "",
            "Encoder API: [Sentence Transformers documentation]"
            "(https://sbert.net/docs/package_reference/sentence_transformer/model.html).",
        ]
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    args = build_parser().parse_args()
    settings = Settings()
    torch.manual_seed(42)
    if _path(args.output).resolve() == _path(args.markdown).resolve():
        raise ValueError("JSON and Markdown output paths must differ")
    profiles = [
        EmbeddingProfile.model_validate(value)
        for value in json.loads(_path(args.profiles).read_text(encoding="utf-8"))
    ]
    if not profiles or len({profile.name for profile in profiles}) != len(profiles):
        raise ValueError("Profiles must be nonempty with unique names")
    if args.overlap >= args.chunk_size:
        raise ValueError("overlap must be smaller than chunk-size")
    queries_path = _path(args.queries)
    source_queries = read_queries(queries_path, SourceEvaluationQuery)
    codec = HuggingFaceTokenCodec.from_pretrained(settings.model_name, settings.model_revision)
    documents = load_documents(_path(args.corpus))
    chunks = build_chunks(documents, RecursiveChunker(codec, args.chunk_size, args.overlap))
    queries = resolve_queries(source_queries, chunks)
    created = datetime.now(UTC).isoformat()
    results: list[EmbeddingBenchmarkResult] = []
    for profile in profiles:
        print(f"Benchmarking {profile.name}...", flush=True)
        started = perf_counter()
        embedder = SentenceTransformerEmbedder(
            profile.model_name, profile.revision, args.device, batch_size=profile.batch_size
        )
        _synchronize(embedder.device)
        load_ms = (perf_counter() - started) * 1_000
        results.append(
            benchmark_embedding(
                embedder,
                profile,
                chunks,
                queries,
                repetitions=args.repetitions,
                warmup_runs=args.warmup_runs,
                top_k=args.top_k,
                model_load_ms=load_ms,
                model_metadata=dict(embedder.metadata()),
            )
        )
        device = embedder.device
        del embedder
        gc.collect()
        if device.type == "mps":
            torch.mps.empty_cache()
        elif device.type == "cuda":
            torch.cuda.empty_cache()
    fingerprint = hashlib.sha256(
        "\n".join(chunk.model_dump_json() for chunk in chunks).encode("utf-8")
    ).hexdigest()
    report = {
        "schema_version": 1,
        "stage": 23,
        "created_at": created,
        "environment": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "torch": torch.__version__,
            "torch_threads": torch.get_num_threads(),
            **{
                name: version(name)
                for name in ("transformers", "sentence-transformers", "qdrant-client")
            },
        },
        "corpus": {
            "path": str(args.corpus),
            "documents": len(documents),
            "chunks": len(chunks),
            "chunks_sha256": fingerprint,
        },
        "dataset": {
            "path": str(args.queries),
            "sha256": hashlib.sha256(queries_path.read_bytes()).hexdigest(),
            "queries": len(queries),
            "resolved_queries": [query.model_dump(mode="json") for query in queries],
        },
        "configuration": {
            "top_k": args.top_k,
            "chunk_strategy": "recursive",
            "chunk_size": args.chunk_size,
            "overlap": args.overlap,
            "tokenizer": settings.model_name,
            "tokenizer_revision": settings.model_revision,
            "distance": "cosine",
            "repetitions": args.repetitions,
            "warmup_runs": args.warmup_runs,
            "seed": 42,
            "profile_order": [profile.name for profile in profiles],
        },
        "results": [result.model_dump(mode="json") for result in results],
    }
    output, markdown = _path(args.output), _path(args.markdown)
    output.parent.mkdir(parents=True, exist_ok=True)
    markdown.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    markdown.write_text(render_markdown(results, args.top_k, created), encoding="utf-8")
    print(f"Wrote {output}\nWrote {markdown}")


if __name__ == "__main__":
    main()
